import {readFile, mkdir, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const packagePath = require.resolve('@iconify-json/hugeicons/package.json');
const pkg = JSON.parse(await readFile(packagePath, 'utf8'));
const collection = JSON.parse(await readFile(require.resolve('@iconify-json/hugeicons/icons.json'), 'utf8'));

// Keep semantic names stable so every app surface uses the same icon family.
const names = {
  sidebar: 'sidebar-left', folder: 'folder-01', chevron: 'arrow-right-01',
  down: 'arrow-down-01', back: 'arrow-left-01', arrowLeft: 'arrow-left-02',
  arrowRight: 'arrow-right-02', grid: 'grid-view', image: 'image-01',
  video: 'video-01', audio: 'music-note-01', file: 'file-01', box: 'package',
  star: 'star', lock: 'square-lock-01', refresh: 'refresh', export: 'upload-01',
  import: 'download-01', search: 'search-01', list: 'left-to-right-list-bullet',
  close: 'cancel-01', tag: 'tag-01', settings: 'settings-01', layers: 'layers-01',
  edit: 'pencil-edit-02', users: 'user-group', play: 'play', pause: 'pause',
  rewind: 'go-backward-10-sec', volumeHigh: 'volume-high', volumeLow: 'volume-low',
  volumeOff: 'volume-off', fullscreenEnter: 'full-screen', fullscreenExit: 'shrink',
  pipEnter: 'picture-in-picture-on', pipExit: 'picture-in-picture-exit',
  airplay: 'airplay', cast: 'cast', captions: 'closed-caption',
  check: 'tick-02', switches: 'sliders-horizontal', speed: 'dashboard-speed-01',
  speech: 'speech', spinner: 'loading-03', restart: 'replay',
};
const markup = {};
for (const [alias, name] of Object.entries(names)) {
  const data = collection.icons[name];
  if (!data || data.rotate || data.hFlip || data.vFlip) throw new Error(`Unsupported or missing Hugeicons icon: ${name}`);
  const width = data.width ?? collection.width ?? 24;
  const height = data.height ?? collection.height ?? 24;
  markup[alias] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="24" height="24" fill="none" aria-hidden="true" focusable="false" data-icon-name="hugeicons:${name}">${data.body}</svg>`;
}
const lock = JSON.parse(await readFile(new URL('../package-lock.json', import.meta.url), 'utf8'));
const outputs = {
  'check.svg': markup.check + '\n',
  'icons.js': `// Generated by scripts/generate-icons.mjs from ${pkg.name}@${pkg.version}.\n// Hugeicons (MIT); see LICENSE.txt. Do not edit by hand.\nexport const iconMarkup = ${JSON.stringify(markup, null, 2)};\n`,
  'VENDORED.json': JSON.stringify({
    package: pkg.name, version: pkg.version, license: pkg.license,
    source: pkg.homepage,
    licenseSource: 'https://github.com/hugeicons/hugeicons-react/blob/main/LICENSE.md',
    integrity: lock.packages['node_modules/@iconify-json/hugeicons'].integrity,
    icons: names,
  }, null, 2) + '\n',
};
const folder = new URL('../frontend/vendor/hugeicons/', import.meta.url);
if (!process.argv.includes('--check')) await mkdir(folder, {recursive: true});
for (const [name, content] of Object.entries(outputs)) {
  const destination = new URL(name, folder);
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== content) throw new Error(`Outdated ${name}; run npm run icons:generate`);
  } else await writeFile(destination, content);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${Object.keys(markup).length} local Hugeicons icons (${pkg.version}).`);
